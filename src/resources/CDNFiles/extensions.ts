export type FileCategory = keyof typeof FILE_EXTENSION_CATEGORIES
type FileExtensionCategories = typeof FILE_EXTENSION_CATEGORIES

type ExtractExtensions<T> = T extends readonly (infer U)[] ? U : never

type ExtensionsToCategory = {
  [K in keyof FileExtensionCategories as ExtractExtensions<FileExtensionCategories[K]>]: K;
}
export const EXTENSION_TO_CATEGORY_MAP = Object.fromEntries(
  Object.entries(FILE_EXTENSION_CATEGORIES).flatMap(([category, extensions]) => extensions.map(extension => [extension, category])),
) as ExtensionsToCategory

export type SupportedFileExtensions = keyof ExtensionsToCategory

